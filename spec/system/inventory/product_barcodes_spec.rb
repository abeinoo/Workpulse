require "rails_helper"

# Barcodes in a real browser: the × of a saved barcode removes it on Save; a
# generated barcode removed before Save leaves nothing; on the counting screen
# an additional barcode focuses the product's existing row (never a duplicate).
RSpec.describe "Product barcodes (browser)", type: :system do
  let(:business) { create(:business) }
  let(:owner)    { create(:user, :owner, business: business) }
  let!(:product) do
    business.products.create!(name: "Argan Oil", sku: "AO-1", initial_cost_price: 1, average_cost_price: 1).tap do |p|
      p.product_barcodes.create!(barcode: "111", barcode_type: "manufacturer", is_primary: true)
      p.product_barcodes.create!(barcode: "222", barcode_type: "carton", is_primary: false)
    end
  end

  # Rows as the user sees them: Capybara matches only rendered (visible) elements,
  # so a row merely carrying [hidden] but still displayed would be counted.
  def rows_css = "[data-line-items-target='rows'] [data-line-row]"
  def barcode_rows = all(rows_css)
  def save! = find("[data-testid='product-save'], #product-form [type='submit']", match: :first).click

  before { sign_in owner }

  it "× on a saved barcode removes it on Save, and it stays removed after reload" do
    visit edit_inventory_product_path(product)
    expect(barcode_rows.size).to eq(2)
    within(barcode_rows.last) { find("button[data-action='line-items#remove']").click }
    expect(page).to have_css(rows_css, count: 1)
    expect(product.product_barcodes.count).to eq(2) # nothing written before Save

    save!
    expect(page).to have_text("All changes saved.")
    expect(product.product_barcodes.reload.pluck(:barcode)).to eq(%w[111])
    visit edit_inventory_product_path(product)
    expect(barcode_rows.map { |row| row.find("input[name$='[barcode]']").value }).to eq(%w[111])
  end

  it "acceptance: remove every barcode, Save, reopen — the product has no barcodes; one can be added again" do
    visit edit_inventory_product_path(product)
    2.times { first(rows_css).find("button[data-action='line-items#remove']").click }
    expect(page).to have_no_css(rows_css)
    save!
    expect(page).to have_text("All changes saved.")
    expect(product.product_barcodes.reload).to be_empty

    visit edit_inventory_product_path(product)
    expect(page).to have_no_css(rows_css)                       # no spare blank row
    expect(page).to have_css("[data-controller~='barcode-list'] [data-line-items-target='emptyState']", visible: true)
    expect(ProductBarcode.where(product: product).count).to eq(0) # nothing generated by opening it

    click_button I18n.t("inventory.products.add_barcode")
    expect(page).to have_css(rows_css, count: 1)
    first(rows_css).find("input[name$='[barcode]']").fill_in(with: "333")
    save!
    expect(page).to have_text("All changes saved.")
    expect(product.product_barcodes.reload.pluck(:barcode)).to eq(%w[333])
  end

  it "a generated barcode removed before Save is never created; one kept is saved with the product" do
    visit edit_inventory_product_path(product)
    expect { click_button I18n.t("inventory.products.generate_barcode"); expect(page).to have_css(rows_css, count: 3) }
      .not_to change(ProductBarcode, :count)
    within(barcode_rows.last) { find("button[data-action='line-items#remove']").click }
    save!
    expect(page).to have_text("All changes saved.")
    expect(product.product_barcodes.reload.pluck(:barcode)).to contain_exactly("111", "222")

    visit edit_inventory_product_path(product)
    click_button I18n.t("inventory.products.generate_barcode")
    expect(page).to have_css(rows_css, count: 3)
    generated = barcode_rows.last.find("input[name$='[barcode]']").value
    save!
    expect(page).to have_text("All changes saved.")
    expect(product.product_barcodes.reload.pluck(:barcode)).to contain_exactly("111", "222", generated)
  end

  it "New product: saved without any barcode creates none; Generate Barcode then Save creates exactly that one" do
    visit new_inventory_product_path
    fill_in "product_name", with: "Plain"
    fill_in "product_sku", with: "PL-1"
    save!
    expect(page).to have_text(I18n.t("inventory.products.created"))
    expect(business.products.find_by!(sku: "PL-1").product_barcodes).to be_empty

    visit new_inventory_product_path
    fill_in "product_name", with: "Generated"
    fill_in "product_sku", with: "GN-1"
    click_button I18n.t("inventory.products.generate_barcode")
    expect(page).to have_field(type: "text", with: /\A1\d{7}\z/) # the generated internal code is in a row
    code = all(rows_css).map { |row| row.find("input[name$='[barcode]']").value }.compact_blank.sole
    expect(ProductBarcode.where(barcode: code)).to be_empty # unsaved until Save
    save!
    expect(page).to have_text(I18n.t("inventory.products.created"))
    expect(business.products.find_by!(sku: "GN-1").product_barcodes.pluck(:barcode, :barcode_type)).to eq([ [ code, "internal" ] ])
  end

  it "scanning an additional barcode on the counting screen focuses the product's row instead of adding one" do
    warehouse = business.warehouses.create!(name: "Main")
    counter = user_with_stock_permissions(business, :view_inventory, :manage_stock_counts)
    count = record_stock_count!(business: business, warehouse: warehouse, counter: counter, lines: [])
    sign_in counter
    visit edit_inventory_stock_count_path(count)
    rows_before = all("tbody tr[data-product-id='#{product.id}']").size
    expect(rows_before).to eq(1)

    scanner = find("[data-barcode-scanner-target='input']")
    scanner.fill_in(with: "222")
    scanner.send_keys(:enter)
    expect(page).to have_css("tbody tr[data-product-id='#{product.id}']", count: 1)
    expect(page.evaluate_script("document.activeElement.closest('tr')?.dataset.productId")).to eq(product.id.to_s)
  end
end
