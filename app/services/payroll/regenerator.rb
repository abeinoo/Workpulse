module Payroll
  # Safe payroll regeneration for super admins.
  # Only operates on draft periods. Delegates actual computation to
  # PeriodGenerator (which already clears stale entries idempotently)
  # and writes a PayrollAuditLog so the action is traceable.
  class Regenerator
    Result = Struct.new(:success, :period, :error, keyword_init: true) do
      def success? = success
    end

    def self.call(period:, regenerated_by:)
      new(period: period, regenerated_by: regenerated_by).call
    end

    def initialize(period:, regenerated_by:)
      @period          = period
      @regenerated_by  = regenerated_by
    end

    def call
      unless @period.draft?
        return err("Only draft periods can be regenerated. Reset the period to draft first.")
      end

      # Capture snapshot before destroying existing entries so diffs are available.
      Payroll::SnapshotService.call(period: @period, taken_by: @regenerated_by)

      previous_entry_count = @period.payroll_entries.count
      # Preserve management overtime overrides across the rebuild (entries are
      # destroyed and recreated by PeriodGenerator). Captured by user_id.
      saved_overrides = capture_overtime_overrides
      # Preserve manual-deduction waivers the same way, keyed by (user_id, source).
      saved_waivers   = capture_deduction_waivers
      # Preserve attendance-penalty waivers the same way, keyed by (user_id, source).
      saved_penalties = capture_penalty_reviews

      regenerated = Payroll::PeriodGenerator.call(
        business:     @period.business,
        year:         @period.period_year,
        month:        @period.period_month,
        generated_by: @regenerated_by
      )

      reapply_overtime_overrides(regenerated, saved_overrides)
      reapply_deduction_waivers(regenerated, saved_waivers)
      reapply_penalty_reviews(regenerated, saved_penalties)

      PayrollAuditLog.create!(
        payroll_period: regenerated,
        actor:          @regenerated_by,
        action_type:    :regenerated,
        from_status:    "draft",
        to_status:      "draft",
        metadata:       JSON.generate(
          previous_entry_count: previous_entry_count,
          new_entry_count:      regenerated.payroll_entries.count,
          regenerated_at:       Time.current.iso8601
        )
      )

      Rails.logger.info("[Payroll::Regenerator] period=#{regenerated.id} #{@period.period_label} regenerated by user=#{@regenerated_by.id} entries=#{regenerated.payroll_entries.count}")
      Result.new(success: true, period: regenerated)
    rescue ArgumentError, RuntimeError => e
      Rails.logger.warn("[Payroll::Regenerator] period=#{@period.id} failed: #{e.message}")
      Result.new(success: false, error: e.message)
    rescue StandardError => e
      Rails.logger.error("[Payroll::Regenerator] period=#{@period.id} unexpected error: #{e.class}: #{e.message}\n#{e.backtrace.first(5).join("\n")}")
      Result.new(success: false, error: e.message)
    end

    private

    # Snapshot the override decision for every overridden entry, keyed by user_id.
    def capture_overtime_overrides
      @period.payroll_entries.where.not(overtime_override_mode: nil).map do |e|
        [ e.user_id, {
          mode:                e.overtime_override_mode,
          approved_minutes:    e.approved_overtime_minutes,
          approved_pay:        e.approved_overtime_pay,
          calculated_minutes:  e.calculated_overtime_minutes,
          calculated_pay:      e.calculated_overtime_pay,
          reason:              e.overtime_override_reason,
          overridden_by_id:    e.overtime_overridden_by_id,
          overridden_at:       e.overtime_overridden_at
        } ]
      end.to_h
    end

    # Re-apply saved overrides to the freshly generated entries, clamping the
    # approved value to the new calculated overtime and flagging the override as
    # stale when the calculated value changed (prompts a re-review).
    def reapply_overtime_overrides(period, saved_overrides)
      return if saved_overrides.empty?

      period.payroll_entries.where(user_id: saved_overrides.keys).find_each do |entry|
        prev = saved_overrides[entry.user_id]
        new_calc_minutes = entry.calculated_overtime_minutes.to_i
        new_calc_pay     = entry.calculated_overtime_pay.to_f

        # Calculated overtime vanished — drop the override entirely.
        next if new_calc_minutes.zero? || new_calc_pay <= 0

        if prev[:mode] == "amount"
          approved_pay     = [ prev[:approved_pay].to_f, new_calc_pay ].min.round(2)
          approved_minutes = (new_calc_minutes * approved_pay / new_calc_pay).round
        else # minutes
          approved_minutes = [ prev[:approved_minutes].to_i, new_calc_minutes ].min
          approved_pay     = (new_calc_pay * approved_minutes / new_calc_minutes).round(2)
        end

        stale = new_calc_minutes != prev[:calculated_minutes].to_i ||
                (new_calc_pay - prev[:calculated_pay].to_f).abs >= 0.01

        entry.update!(
          overtime_override_mode:    prev[:mode],
          approved_overtime_minutes: approved_minutes,
          approved_overtime_pay:     approved_pay,
          overtime_override_reason:  prev[:reason],
          overtime_overridden_by_id: prev[:overridden_by_id],
          overtime_overridden_at:    prev[:overridden_at],
          overtime_override_stale:   stale
        )
        entry.recalculate_totals!
      end
    end

    # Snapshot every waived manual deduction, keyed by [user_id, adjustment_id].
    # The waiver lives at the payroll layer; the source PayrollAdjustment is stable
    # across regeneration (it is never modified), so its id is a reliable join key.
    def capture_deduction_waivers
      PayrollLineItem
        .joins(:payroll_entry)
        .where(payroll_entries: { payroll_period_id: @period.id })
        .where(item_type: "manual_deduction", deduction_waived: true)
        .includes(:payroll_entry)
        .each_with_object({}) do |li, memo|
          next if li.source_id.blank?
          memo[[ li.payroll_entry.user_id, li.source_id ]] = {
            reason:     li.deduction_waiver_reason,
            waived_by_id: li.deduction_waived_by_id,
            waived_at:  li.deduction_waived_at
          }
        end
    end

    # Re-apply saved waivers to the freshly generated manual-deduction line items,
    # matched by [user_id, source adjustment id], then recompute affected entries.
    def reapply_deduction_waivers(period, saved_waivers)
      return if saved_waivers.empty?

      touched_entry_ids = []

      period.payroll_entries.includes(:payroll_line_items).find_each do |entry|
        entry.payroll_line_items.each do |li|
          next unless li.manual_deduction? && li.source_id.present?
          prev = saved_waivers[[ entry.user_id, li.source_id ]]
          next unless prev

          li.update!(
            deduction_waived:        true,
            deduction_waiver_reason: prev[:reason],
            deduction_waived_by_id:  prev[:waived_by_id],
            deduction_waived_at:     prev[:waived_at]
          )
          touched_entry_ids << entry.id
        end
      end

      PayrollEntry.where(id: touched_entry_ids.uniq)
                  .includes(:payroll_line_items)
                  .each(&:recalculate_totals!)
    end

    # Snapshot every waived attendance-penalty item, keyed by [user_id, source_id].
    # The source AttendanceRecord is stable across regeneration, so its id is a
    # reliable join key (mirrors capture_deduction_waivers above).
    def capture_penalty_reviews
      PayrollLineItem
        .joins(:payroll_entry)
        .where(payroll_entries: { payroll_period_id: @period.id })
        .where(item_type: Payroll::EntryRecalculator::ATTENDANCE_PENALTY_TYPES, review_status: "waived")
        .includes(:payroll_entry)
        .each_with_object({}) do |li, memo|
          next if li.source_id.blank?
          memo[[ li.payroll_entry.user_id, li.source_id ]] = {
            reviewed_by_id: li.reviewed_by_id,
            reviewed_at:    li.reviewed_at,
            review_notes:   li.review_notes
          }
        end
    end

    # Re-apply saved attendance-penalty waivers to the freshly generated line
    # items, matched by [user_id, source AttendanceRecord id].
    def reapply_penalty_reviews(period, saved_reviews)
      return if saved_reviews.empty?

      touched_entry_ids = []

      period.payroll_entries.includes(:payroll_line_items).find_each do |entry|
        entry.payroll_line_items.each do |li|
          next unless Payroll::EntryRecalculator::ATTENDANCE_PENALTY_TYPES.include?(li.item_type) && li.source_id.present?
          prev = saved_reviews[[ entry.user_id, li.source_id ]]
          next unless prev

          li.update!(
            review_status:  "waived",
            reviewed_by_id: prev[:reviewed_by_id],
            reviewed_at:    prev[:reviewed_at],
            review_notes:   prev[:review_notes]
          )
          touched_entry_ids << entry.id
        end
      end

      PayrollEntry.where(id: touched_entry_ids.uniq)
                  .includes(:payroll_line_items)
                  .each(&:recalculate_totals!)
    end

    def err(message)
      Result.new(success: false, error: message)
    end
  end
end
